def svg(name, width=None, extra=""):
    s = (LOGO / name).read_text()
    s = re.sub(r'\swidth="[^"]*"', "", s, count=1)
    s = re.sub(r'\sheight="[^"]*"', "", s, count=1)
    style = f'style="width:{width};height:auto;{extra}"' if width else ""
    return s.replace("<svg ", f"<svg {style} ", 1)


