def swatches(scale, star=None):
    out = []
    for step, hexv, onp, oni in scale:
        mark = " ★" if step == star else ""
        out.append(
            f'<div style="flex:1;min-width:0">'
            f'<div style="height:74px;background:{hexv};border-radius:6px;'
            f'border:1px solid rgba(12,26,21,.08)"></div>'
            f'<div style="margin-top:7px;font:500 10px/1.35 var(--font-mono);'
            f'color:var(--kc-text)">{step}{mark}</div>'
            f'<div style="font:400 10px/1.35 var(--font-mono);color:var(--kc-textMuted)">'
            f'{hexv}</div>'
            f'<div style="font:400 9px/1.4 var(--font-mono);color:var(--kc-textMuted);'
            f'margin-top:3px">{onp:.2f} / {oni:.2f}</div>'
            f"</div>"
        )
    return "".join(out)


def eyebrow(t):
    return (
        f'<p style="font:500 11px/1.2 var(--font-mono);letter-spacing:.08em;'
        f'text-transform:uppercase;color:var(--kc-brandText);margin:0 0 10px">{t}</p>'
    )


def h2(t):
    return (
        f'<h2 style="font:700 30px/1.1 var(--font-display);letter-spacing:-.02em;'
        f'margin:0 0 6px;color:var(--kc-text)">{t}</h2>'
    )


def note(t):
    return (
        f'<p style="font:400 13px/1.6 var(--font-body);color:var(--kc-textMuted);'
        f'margin:0 0 26px;max-width:78ch">{t}</p>'
    )


def panel(inner, dark=False, pad=26):
    bg = "var(--kc-stone-900)" if dark else "var(--kc-surface)"
    return (
        f'<div style="background:{bg};border:1px solid var(--kc-border);'
        f'border-radius:10px;padding:{pad}px">{inner}</div>'
    )


def cap(t, dark=False):
    c = "var(--kc-stone-400)" if dark else "var(--kc-textMuted)"
    return (
        f'<p style="font:400 10px/1.3 var(--font-mono);text-transform:uppercase;'
        f'letter-spacing:.06em;color:{c};margin:14px 0 0">{t}</p>'
    )


